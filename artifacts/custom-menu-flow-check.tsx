import React from 'react';
import { createRoot } from 'react-dom/client';
import { configureStore } from '@reduxjs/toolkit';
import { Provider } from 'react-redux';
import { MemoryRouter } from 'react-router-dom';
import { ThemeProvider, createTheme, CssBaseline, Box, Typography } from '@mui/material';
import api from '../src/api/axios';
import inventory from '../src/features/inventory/inventorySlice';
import { DEFAULT_APP_SETTINGS } from '../src/features/settings/settingsSlice';
import CreateDigitalMenuPage from '../src/pages/DigitalMenus/CreateDigitalMenuPage';
const products = (await fetch('/artifacts/section-menu-inventory.json').then(response=>response.json())).map(item=>({...item,salePrice:item.price}));
const branded = new URLSearchParams(location.search).has('branded');
const incomplete = new URLSearchParams(location.search).has('incomplete');
const user = { id: 'ui-test', name: 'UI test', role: 'super_admin', appearance: branded ? { themeColor: '#783925', backgroundColor: '#fff8ed', fontColor: '#222222', logo: '' } : { themeColor: '#0ea5a5', fontColor: '', logo: '' } };
api.get = async url => {
    if (url === '/products') return { data: products };
    if (url === '/digital-menus/ai/capabilities') return { data: { features: ['custom-menu-style', 'custom-menu-copy', 'template-menu-style', 'section-images'] } };
    return { data: [] };
};
api.post = async (url, body) => {
    if (url !== '/digital-menus/ai/suggest') throw new Error('Database writes are disabled for this UI test');
    if (!body.includeStyle || body.currentDesign.templateId !== 'custom') throw new Error('The custom menu must request a complete design');
    if (!branded && (body.brand.theme || body.brand.logo || body.brand.colors.length)) throw new Error('Application defaults must not be treated as restaurant branding');
    if (branded && (!body.brand.theme.includes('#783925') || !body.brand.colors.includes('#fff8ed'))) throw new Error('Saved theme was not included');
    const data = await fetch('/artifacts/section-menu-suggestions.json').then(response => response.json());
    if (incomplete) delete data.style;
    return { data };
};
const store = configureStore({ reducer: { inventory, auth: () => ({ user }), settings: () => ({ currency: 'PKR', app: { ...DEFAULT_APP_SETTINGS, restaurantEnabled: true } }) } });
createRoot(document.getElementById('test-root')!).render(<Provider store={store}><ThemeProvider theme={createTheme({ palette: { primary: { main: '#0aa4a7' } } })}><CssBaseline /><MemoryRouter><Box sx={{ maxWidth: 1200, m: 'auto', p: 3 }}><Typography variant="caption" color="text.secondary">Isolated UI verification · AI results from Google · no menus saved</Typography><CreateDigitalMenuPage /></Box></MemoryRouter></ThemeProvider></Provider>);
