import React from 'react';
import { createRoot } from 'react-dom/client';
import { configureStore } from '@reduxjs/toolkit';
import { Provider } from 'react-redux';
import { MemoryRouter, Routes, Route } from 'react-router-dom';
import { ThemeProvider, createTheme, CssBaseline } from '@mui/material';
import api from '../src/api/axios';
import { DEFAULT_APP_SETTINGS } from '../src/features/settings/settingsSlice';
import PublicMenuPage from '../src/pages/DigitalMenus/PublicMenuPage';
import { newMenuBlock } from '../src/pages/DigitalMenus/menuContent';
import { PLAIN_MENU_DESIGN } from '../src/pages/DigitalMenus/menuTemplates';
import { sectionPhoto } from '../src/pages/DigitalMenus/sectionImages';
const suggestion = await fetch('/artifacts/section-menu-suggestions.json').then(response=>response.json());
const products = (await fetch('/artifacts/section-menu-inventory.json').then(response=>response.json())).map(item=>({...item,salePrice:item.price}));
const design = {...PLAIN_MENU_DESIGN,...suggestion.style};
const content = [newMenuBlock('title',design.textColor,'The Kitchen'),...suggestion.sections.map(section=>({...newMenuBlock('section',design.accentColor,section.name),span:3,productIds:section.productIds,sectionImage:sectionPhoto(section.imageKey)}))];
api.get = async url=>{if(url==='/digital-menus/public/sample')return{data:{menu:{name:'The Kitchen',tableName:'Table 1',productIds:products.map(product=>product.id),design,content,orderingEnabled:true,pageCount:1},products,deals:[]}};throw new Error('Unexpected test request');};
api.post = async()=>{throw new Error('Ordering is disabled in this isolated test');};
const store = configureStore({reducer:{auth:()=>({user:null}),settings:()=>({currency:'PKR',app:DEFAULT_APP_SETTINGS})}});
createRoot(document.getElementById('test-root')!).render(<Provider store={store}><ThemeProvider theme={createTheme()}><CssBaseline/><MemoryRouter initialEntries={['/menu/sample']}><Routes><Route path="/menu/:token" element={<PublicMenuPage/>}/></Routes></MemoryRouter></ThemeProvider></Provider>);
